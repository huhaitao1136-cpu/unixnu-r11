#!/usr/bin/env python3
"""make-binaries.py — 把从 R11 自家 xbl 里抽出来的厂商 DXE，组装成
Mu-Silicium 期望的 `Binaries/r11/` 目录（INF + PE32 + RawFiles）。

输入：
  - extract-fv.py 的输出目录（含 *.efi 与 index.txt）
  - 平台包目录（读 Include/*.inc 与 *.fdf 里 `Binaries/r11/...inf` 的全部引用）

用法：
  python make-binaries.py --extract R11-backup/extract/xbl \
      --platform ../uefi-r11/Platforms/OPPO/r11Pkg \
      --out ../uefi-r11/Binaries/r11
"""
from __future__ import annotations

import argparse
import re
import shutil
import sys
from pathlib import Path

# INF 里的目录名 → xbl 里实际的模块名（其余同名）
MAP = {
    "ChipInfoDxe": "ChipInfo",
    "DALSYSDxe": "DALSys",
    "HWIODxe": "HWIODxeDriver",
    "I2CDxe": "I2C",
    "PlatformInfoDxe": "PlatformInfoDxeDriver",
    "PmicDxeLa": "PmicDxe",
    "QcomChargerDxeLA": "QcomChargerDxeLA",
    "RngDxe": "RngDxe",
    "SPIDxe": "SPI",
    "SPMIDxe": "SPMI",
    "TLMMDxe": "DALTLMM",
    "GLinkDxe": "GlinkDxe",
    "PmicDxe": "PmicDxe",
    "TzDxeLA": "TzDxe",
    "UFSDxe": "UFSDxe",
}

INF_TMPL = """##  Auto-generated by make-binaries.py from the device's own XBL.
##  Vendor binary, not built from source.

[Defines]
  INF_VERSION    = 0x00010005
  BASE_NAME      = {base}
  FILE_GUID      = {guid}
  MODULE_TYPE    = DXE_DRIVER
  VERSION_STRING = 1.0

[Binaries]
  PE32|{base}.efi
"""


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--extract", required=True)
    ap.add_argument("--platform", required=True)
    ap.add_argument("--out", required=True)
    args = ap.parse_args()

    ext = Path(args.extract)
    plat = Path(args.platform)
    out = Path(args.out)

    # 1) 平台包引用了哪些 INF
    refs: set[str] = set()
    for f in list(plat.rglob("*.inc")) + list(plat.rglob("*.fdf")):
        for m in re.finditer(r"Binaries/r11/(\S+\.inf)", f.read_text(encoding="utf-8", errors="replace")):
            refs.add(m.group(1))
    print(f"平台引用 {len(refs)} 个 INF")

    # 2) 索引：模块名 → (efi 路径, guid)
    index: dict[str, tuple[Path, str]] = {}
    idx_file = ext / "index.txt"
    guids: dict[str, str] = {}
    if idx_file.exists():
        for line in idx_file.read_text(encoding="utf-8").splitlines():
            parts = line.split("\t")
            if len(parts) >= 4 and parts[0] in ("PE32", "TE", "PIC"):
                guids.setdefault(parts[2], parts[3])
    for efi in sorted(ext.glob("*.efi")):
        name = re.sub(r"_\d+$", "", efi.stem)
        index.setdefault(name, (efi, guids.get(name, "")))

    made, missing = [], []
    for rel in sorted(refs):
        parts = rel.split("/")
        inf_name = parts[-1][:-4]           # 去掉 .inf
        dir_name = parts[-2]
        mod = MAP.get(inf_name, inf_name)
        hit = index.get(mod) or index.get(inf_name)
        if not hit:
            missing.append(rel)
            continue
        efi, guid = hit
        if not guid:
            import uuid
            guid = str(uuid.uuid5(uuid.NAMESPACE_DNS, f"r11-qcom-{inf_name}"))
        dst = out / "QcomPkg" / "Drivers" / dir_name
        dst.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(efi, dst / f"{inf_name}.efi")
        (dst / f"{inf_name}.inf").write_text(
            INF_TMPL.format(base=inf_name, guid=guid), encoding="utf-8")
        made.append(f"{dir_name}/{inf_name}.inf  <- {efi.name} ({efi.stat().st_size} B)")

    # 3) RawFiles
    raw_src = ext / "raw"
    raw_dst = out / "RawFiles"
    raw_dst.mkdir(parents=True, exist_ok=True)
    raw_want = ["uefiplat.cfg", "BDS_Menu.cfg", "SecParti.cfg", "tracer_event.cfg",
                "QcomChargerCfg.cfg", "BATTERY.PROVISION"]
    raw_ok, raw_missing = [], []
    for n in raw_want:
        s = raw_src / n
        if s.exists():
            shutil.copyfile(s, raw_dst / n)
            raw_ok.append(n)
        else:
            raw_missing.append(n)

    print(f"\n生成 {len(made)} 个驱动：")
    for m in made:
        print("  " + m)
    if missing:
        print(f"\n缺失 {len(missing)} 个（需要另行从其他分区提取或用 Mu 自带实现）：")
        for m in missing:
            print("  " + m)
    print(f"\nRawFiles 已复制: {', '.join(raw_ok) or '(无)'}")
    if raw_missing:
        print(f"RawFiles 缺失: {', '.join(raw_missing)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
